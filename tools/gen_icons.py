# Generates src/ui/icons.h from Lucide codepoints and subsets lucide.ttf to the icons used.
import json, sys, subprocess
names = """user users user-plus settings refresh-cw log-in log-out trash-2 copy gamepad-2 search x check eye-off eye
wifi-off monitor folder-open link external-link star pin pencil plus grip-vertical moon sun circle info triangle-alert
shield-alert zap power layers list layout-grid ellipsis ellipsis-vertical house keyboard sticky-note image rotate-ccw chevron-right
chevron-down chevron-up circle-check ban clock play save archive download hard-drive sliders-horizontal palette languages
ghost circle-dot globe hash id-card shield lock cpu rocket sparkles panel-left arrow-left badge-check user-round-x
terminal app-window square-plus folder file-text history timer flame layout-list arrow-up-right mouse-pointer-click
circle-help gauge plug badge-alert bookmark command""".split()
cp = json.load(open(sys.argv[1]))
out = ["// Generated by tools/gen_icons.py — Lucide icon font codepoints (ISC license)", "#pragma once", ""]
used = []
for n in names:
    if n not in cp:
        print("missing", n); continue
    c = cp[n]; used.append(c)
    b = chr(c).encode("utf-8")
    ident = "ICON_" + n.upper().replace("-", "_")
    out.append('#define %-28s "%s"' % (ident, "".join("\\x%02x" % x for x in b)))
out.append("")
out.append("#define ICON_MIN 0x%x" % min(used))
out.append("#define ICON_MAX 0x%x" % max(used))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
open(sys.argv[3], "w").write(",".join("U+%04X" % c for c in used))
print(len(used), "icons")
